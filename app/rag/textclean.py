# ======================================================================
# 输出文本清洗工具（全站统一入口）
#
# 背景：用户明确要求「最终答案里不能出现双引号」。之前在各端点里各写了一份
# _clean，只过滤了 " “ ” 三种字符，但 LLM 偶尔会吐出全角双引号 ＂（U+FF02）、
# 低位双引号 „（U+201E）、书名号式引号 « »（U+00AB/00BB）等变体，导致漏网。
# 这里把「所有双引号族字符」收敛成一张表，供 assistant.py / api.py 统一调用，
# 以后要改策略只动这一个文件。
# ======================================================================

# 所有需要剥掉的「双引号族」字符（单引号 ‘ ’ ' 保留，用户只要求去双引号）
_DOUBLE_QUOTES = (
    "\u0022"  # "  ASCII 双引号
    "\u201c"  # “  左弯双引号
    "\u201d"  # ”  右弯双引号
    "\u201e"  # „  低位双引号（德式）
    "\u201f"  # ‟  高位反向双引号
    "\uff02"  # ＂ 全角双引号
    "\u00ab"  # «  左书名号式引号（法式）
    "\u00bb"  # »  右书名号式引号
    "\u301d"  # 〝 反向双引号（中日排版）
    "\u301e"  # 〞 双引号（中日排版）
)

# str.translate 用的映射表：把上面每个字符都映射成 None（即删除）
_STRIP_TABLE = {ord(ch): None for ch in _DOUBLE_QUOTES}


def strip_double_quotes(text: str) -> str:
    """剥掉文本中所有双引号族字符（流式逐 chunk 调用也安全：单字符替换无跨块问题）。"""
    return (text or "").translate(_STRIP_TABLE)
